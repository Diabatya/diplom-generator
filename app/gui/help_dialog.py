"""Built-in user manual («?» button in the header): a resizable,
scrollable dialog that works fully offline."""

from __future__ import annotations

from PySide6.QtWidgets import (
    QDialog, QDialogButtonBox, QTextBrowser, QVBoxLayout, QWidget,
)

HELP_HTML = """
<h2>Как пользоваться генератором дипломов</h2>
<p>Программа берёт шаблон диплома (PowerPoint или PDF) и список участников
в Excel и создаёт диплом на каждую строку списка. Исходные файлы
не изменяются. Работа ведётся в три шага, указанных вверху окна:
<b>Шаблон и поля → Участники (Excel) → Проверка и генерация</b>.</p>

<h3>Шаг 1. Шаблон и поля</h3>
<p><b>Выбор шаблона.</b> Нажмите «Выбрать файл шаблона (.pptx или .pdf)…»
и укажите файл. Для PowerPoint-шаблона с несколькими слайдами выберите
в списке над превью «Все слайды шаблона на каждую строку» или
«Только слайд N на каждую строку». Стрелки ◀ ▶ листают слайды
для просмотра. Если нужный текст (например, ФИО) вставлен в шаблон
как часть картинки, программа не сможет его заменить — заменяется
только обычный текст.</p>
<p><b>Поля.</b> Кнопка «Добавить поле…» создаёт поле (например,
«ФИО», «Номинация», «Управление»). Выделите поле в списке и кликните по
текстовому блоку на превью (или по строке в списке блоков ниже) —
место привяжется к полю. «Удалить выбранное место» убирает привязку.</p>
<p><b>Способы замены</b> (при клике по блоку предлагаются варианты):<br>
• «Заменить весь текст блока» — текст блока полностью заменяется
значением из Excel;<br>
• «Заменить только фрагмент:» — заменяется выделенная часть,
окружающий текст сохраняется; кнопка «Взять выделенное» подставляет
выделенный фрагмент;<br>
• «Заменить токен» — если в тексте есть пометка вида @@СЛОВО@@,
заменяется только она.</p>
<p><b>Факсимильная подпись.</b> Включите «Добавить подпись на все дипломы»,
выберите «Файл изображения…» (PNG с прозрачным фоном
рекомендуется, JPEG тоже поддерживается), затем «Выделить область на превью»
и растяните рамку мышью. Рамку можно двигать и менять размер
за нижний правый угол; «Убрать» удаляет подпись. Картинка вписывается
в область с сохранением пропорций — без растягивания и обрезки.
Подпись ставится поверх содержимого на каждый выходной слайд.
При смене шаблона или исходного слайда область нужно выделить заново.</p>
<p><b>Сохранение разметки.</b> «Сохранить разметку (.mapping.json)»
записывает привязки рядом с шаблоном; при повторном открытии того же
шаблона программа предложит загрузить их. Если файл подписи был
перемещён или удалён, программа предупредит — просто выберите файл
заново.</p>

<h3>Шаг 2. Участники (Excel)</h3>
<p><b>Стандартный файл.</b> Кнопка «Сохранить пустой Excel…» создаёт
готовый файл participants-template.xlsx: лист «Участники», первая
строка — заголовки «ФИО», «Номинация», «Управление». Участники
заполняются со второй строки, один участник — одна строка.</p>
<p><b>Сопоставление столбцов.</b> После «Выбрать Excel-файл (.xlsx)…»
для каждого поля выберите столбец таблицы. Также доступны:
«Постоянный текст» — одна и та же фраза во всех дипломах;
«Сохранить исходный текст» — текст шаблона остаётся без изменений.
Флажок «Обязательно» означает, что строка с пустой ячейкой будет
пропущена с сообщением в отчёте.</p>
<p><b>Имя файла.</b> «Поле для имени файла» выбирает, откуда брать
название диплома; «Взять только первое слово» оставляет, например,
одну фамилию.</p>
<p><b>Пример.</b> «Сгенерировать пример выбранной строки» создаёт один
диплом — проверьте ФИО, номинацию, длинный текст и положение подписи
до массовой генерации. Примечание: встроенный предпросмотр PPTX
приблизительный — окончательный вид смотрите в PowerPoint.</p>

<h3>Шаг 3. Проверка и генерация</h3>
<p><b>Формат результата.</b> «Один файл со всеми записями» — общий
PowerPoint/PDF, слайд на участника; «Отдельный файл на каждую строку» —
свой файл для каждого.</p>
<p><b>Совпадения имён.</b> Если файл с таким именем уже есть:
«Перезаписать все», «Пропустить существующие (создать только новые)»
или «Добавить суффикс «_2», «_3» к именам».</p>
<p><b>Запуск.</b> «Выбрать папку для результатов…», затем «Начать
генерацию». Ход виден на индикаторе; «Отменить генерацию» останавливает
процесс — уже созданные файлы остаются. «Открыть папку с результатами»
показывает готовые дипломы.</p>

<h3>Результаты и отчёт</h3>
<p>Рядом с результатами создаётся файл-отчёт. Сообщения «требует
проверки», «шрифт уменьшен» или «текст не поместился» означают, что
строку стоит посмотреть глазами — программа уменьшила шрифт или текст
всё же не влез. Строки с пустыми обязательными полями пропускаются
и перечисляются в отчёте.</p>
"""

DIALOG_TITLE = "Как пользоваться генератором дипломов"


def open_help(parent: QWidget | None = None) -> None:
    """Open the modal instruction dialog."""
    dlg = QDialog(parent)
    dlg.setWindowTitle(DIALOG_TITLE)
    dlg.setModal(True)
    dlg.resize(720, 560)
    dlg.setMinimumSize(480, 360)
    v = QVBoxLayout(dlg)
    browser = QTextBrowser()
    browser.setOpenExternalLinks(False)
    browser.setHtml(HELP_HTML)
    v.addWidget(browser, 1)
    bb = QDialogButtonBox(QDialogButtonBox.Close)
    bb.rejected.connect(dlg.reject)
    v.addWidget(bb)
    dlg.exec()
